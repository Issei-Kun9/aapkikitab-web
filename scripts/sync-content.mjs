// Pulls every active product and all website content from the shop's own API (/api/catalog,
// backed by the admin panel's database) and writes src/data/catalog.ts + src/data/site-content.ts.
// Runs before every build. If the API can't be reached, the files already in the repo are kept.
// Usage: CATALOG_URL=https://aapkikitab.in node scripts/sync-content.mjs
import { writeFileSync } from "node:fs";

const base = (process.env.CATALOG_URL || "https://aapkikitab.in").replace(/\/$/, "");
let catalog;
try {
  const r = await fetch(`${base}/api/catalog`, { headers: { "user-agent": "aapkikitab-build" } });
  if (!r.ok) throw new Error(`HTTP ${r.status}`);
  catalog = await r.json();
  if (!catalog?.entries?.product) throw new Error("no products in the reply");
} catch (e) {
  console.error(`sync-content: ${e.message} — keeping the content already in the repo.`);
  process.exit(0);
}

const E = catalog.entries;
// entry → flat object { handle, ...fields } (references already resolved by the API)
const flat = (type) => (E[type] ?? []).map((e) => ({ ...e.fields, handle: e.handle, position: e.position }));
const on = (o) => o.active !== false;
const byPos = (a, b) => (Number(a.position ?? 999) || 999) - (Number(b.position ?? 999) || 999);
const list = (v) => (Array.isArray(v) ? v : []);
const int = (v) => (v === undefined || v === null || v === "" ? undefined : Math.round(Number(v)));
const abs = (u) => (u ? u : "");

const [slides, tiles, budgets, gifts, stores, home, shopInfo, shortcuts, trust, promoTiles, links, policyEntries] = [
  "ak_promo_slide", "ak_tile", "ak_budget", "ak_gift_box", "ak_bookstore", "ak_homepage", "ak_shop_info", "ak_shortcut", "ak_trust_item", "ak_promo_tile", "ak_link", "policy",
].map(flat);

// Tag vocabularies come from the tiles set up in admin, so a new category / mood / exam /
// craft type added there is picked up without touching code.
const tagsOf = (kind) => tiles.filter((t) => t.kind === kind && t.tag).map((t) => String(t.tag).toLowerCase());
const fallback = (live, l) => (live.length ? live : l);
const MOODS = fallback(tagsOf("Mood"), ["feel", "thrill", "learn", "reflect", "love", "grow", "escape", "light"]);
const CATS = fallback(tagsOf("Category"), ["fiction", "mystery-thriller", "self-help", "hindi-literature", "english-literature", "biography-history", "children", "education-exams", "maths-science"]);
const EXAMS = tagsOf("Exam");
const CRAFT_TYPES = fallback(tagsOf("Art & Craft type"), ["art-supplies", "notebooks", "craft-kits", "pens"]);
const HIGHLIGHTS = { "New arrival": "newarrival", Bestseller: "bestseller", Trending: "trending", Featured: "featured", "Book of the day": "book-of-the-day" };

const books = (E.product ?? []).map(({ handle, fields: p }) => {
  const tags = [
    ...list(p.shelves).map((s) => s?.tag),
    ...(p.bookstore?.tag ? [`store:${p.bookstore.tag}`] : []),
    ...list(p.highlights).map((h) => HIGHLIGHTS[h]),
  ].filter(Boolean).map((t) => String(t).toLowerCase());
  const uniq = [...new Set(tags)];
  tags.length = 0;
  tags.push(...uniq);
  const price = Math.round(Number(p.price) || 0);
  const mrp = Math.round(Number(p.mrp) || 0);
  const pick = (vocab) => tags.filter((t) => vocab.includes(t));
  const isNew = tags.includes("newarrival");
  const isCraft = p.kind === "Art & Craft";
  const images = list(p.images);
  return {
    kind: isCraft ? "craft" : "book",
    slug: handle,
    title: p.title ?? handle,
    author: p.author || "Aapki Kitab",
    isbn: p.isbn ?? null,
    publisher: p.publisher ?? "",
    pages: int(p.pages) || 0,
    language: p.language ?? "English",
    edition: p.edition ?? "",
    genre: p.genre ?? "",
    price,
    mrp: mrp > price ? mrp : price,
    rating: 0,
    reviews: 0,
    cover: images[0] ? abs(images[0]) : null,
    ...(images.length > 1 ? { gallery: images.map(abs) } : {}),
    coverTint: "#4b0f8a",
    moods: pick(MOODS),
    exams: pick(EXAMS),
    categories: isCraft ? pick(CRAFT_TYPES) : pick(CATS),
    badges: [...(tags.includes("bestseller") ? ["BESTSELLER"] : []), ...(tags.includes("featured") ? ["FEATURED"] : []), ...(isNew ? ["NEW"] : [])],
    isNew,
    trending: tags.includes("trending") || tags.includes("bestseller"),
    bookOfDay: tags.includes("book-of-the-day"),
    ...(typeof p.stock === "number" && p.stock <= 0 ? { soldOut: true } : {}),
    store: p.bookstore?.tag ?? "abc-bookstore",
    blurb: String(p.description ?? "").slice(0, 400),
  };
});

writeFileSync(
  new URL("../src/data/catalog.ts", import.meta.url),
  `// AUTO-GENERATED by scripts/sync-content.mjs from the admin panel — do not hand-edit.\n` +
    `import type { Book } from "./books";\n` +
    `export const CATALOG_BOOKS: Book[] = ${JSON.stringify(books, null, 2)};\n`,
);
console.log(`sync-content: wrote ${books.length} products.`);

// ---- policy pages: "## heading", "- bullet", blank line = new paragraph ----
const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
const inline = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>").replace(/(https?:\/\/[^\s<]+)/g, '<a href="$1">$1</a>');
function toHtml(text) {
  const out = [];
  let bullets = [];
  let para = [];
  const flushP = () => para.length && (out.push(`<p>${para.map(inline).join("<br>")}</p>`), (para = []));
  const flushL = () => bullets.length && (out.push(`<ul>${bullets.map((b) => `<li>${inline(b)}</li>`).join("")}</ul>`), (bullets = []));
  for (const raw of String(text ?? "").split("\n")) {
    const line = raw.trimEnd();
    if (/^##\s+/.test(line)) { flushP(); flushL(); out.push(`<h2>${inline(line.replace(/^##\s+/, ""))}</h2>`); }
    else if (/^[-•]\s+/.test(line)) { flushP(); bullets.push(line.replace(/^[-•]\s+/, "")); }
    else if (!line.trim()) { flushP(); flushL(); }
    else { flushL(); para.push(line); }
  }
  flushP();
  flushL();
  return out.join("\n");
}
const SECTION = { Shipping: "shipping", "Returns & refunds": "returns", Privacy: "privacy", Terms: "terms" };
const policies = policyEntries
  .filter((p) => SECTION[p.section] && p.body)
  .sort((a, b) => Object.keys(SECTION).indexOf(a.section) - Object.keys(SECTION).indexOf(b.section))
  .map((p) => ({ id: SECTION[p.section], title: p.title, body: toHtml(p.body) }));

const today = new Date().toISOString().slice(0, 10);
const tileOf = (kind, base) => tiles.filter((t) => t.kind === kind && on(t)).sort(byPos)
  .map((t) => ({ slug: t.tag, label: t.label, sub: t.subtitle ?? "", icon: "", href: `/${base}/${t.tag}`, ...(t.image ? { image: abs(t.image) } : {}) }));
const info = shopInfo[0] ?? null;
const content = {
  promos: slides.filter(on).filter((s) => (!s.start_date || s.start_date <= today) && (!s.end_date || s.end_date >= today)).sort(byPos)
    .map((s) => ({ heading: s.heading, lead: s.lead ?? "", book: s.book, note: s.note ?? "", cta: s.button_text || "Shop now", photo: abs(s.photo) })),
  categories: tileOf("Category", "category"),
  moods: tileOf("Mood", "mood"),
  exams: tileOf("Exam", "exam"),
  craftTypes: tiles.filter((t) => t.kind === "Art & Craft type" && on(t)).sort(byPos).map((t) => ({ slug: t.tag, label: t.label })),
  budgets: budgets.filter(on).sort(byPos).map((b) => ({ slug: b.handle, label: b.label, max: int(b.max_price) })),
  giftBoxes: gifts.filter(on).sort(byPos).map((g) => ({ slug: g.handle, name: g.name, items: list(g.contents), price: int(g.price), photo: abs(g.photo), ...(g.product ? { product: g.product } : {}) })),
  stores: stores.filter(on).sort(byPos).map((s) => ({ slug: s.tag, name: s.name, location: s.location, about: s.about ?? "", phone: s.phone ?? "", tag: `store:${s.tag}`, photo: abs(s.photo) })),
  home: home[0] ? Object.fromEntries(Object.entries(home[0]).map(([k, v]) => [k, typeof v === "boolean" ? String(v) : k === "hero_photo" ? abs(v) : v])) : null,
  shop: info && {
    ...Object.fromEntries(Object.entries(info).map(([k, v]) => [k, typeof v === "boolean" ? String(v) : v])),
    payment_methods: list(info.payment_methods),
    free_shipping_above: int(info.free_shipping_above),
    shipping_fee: int(info.shipping_fee),
    return_days: int(info.return_days),
  },
  shortcuts: shortcuts.filter(on).sort(byPos).map((s) => ({ label: s.label, icon: s.icon ?? "Star", href: s.link || "/browse" })),
  trust: trust.filter(on).sort(byPos).slice(0, 4).map((t) => ({ title: t.title, sub: t.subtitle ?? "", icon: t.icon ?? "Check", href: t.link ?? "" })),
  promoTiles: promoTiles.filter(on).sort(byPos).map((t) => ({ title: t.title, sub: t.subtitle ?? "", cta: t.button_text || "Shop Now", href: t.link || "/browse", photo: abs(t.photo), colour: t.colour ?? "Lavender" })),
  links: links.filter(on).sort(byPos).map((l) => ({ label: l.label, href: l.link, placement: l.placement })),
  policies,
};
writeFileSync(
  new URL("../src/data/site-content.ts", import.meta.url),
  `// AUTO-GENERATED by scripts/sync-content.mjs from the admin panel — do not hand-edit.\n` +
    `export const SITE_CONTENT: Record<string, any> | null = ${JSON.stringify(content, null, 2)};\n`,
);
console.log(`sync-content: content — ${content.promos.length} slides, ${content.categories.length + content.moods.length + content.exams.length} tiles, ${content.links.length} links, ${content.policies.length} policies.`);
